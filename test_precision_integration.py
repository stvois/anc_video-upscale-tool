"""Run manually after setup_precision.ps1; performs actual model inference."""
import json
import subprocess
import tempfile
from pathlib import Path
from video_upscaler_core import (
    USER_DATA_DIR, UpscaleSettings, VideoUpscalePipeline, find_ffmpeg, find_ffprobe,
)


def main():
    with tempfile.TemporaryDirectory() as temp:
        root = Path(temp)
        source, output = root / 'source.mp4', root / 'output.mp4'
        subprocess.run([
            find_ffmpeg(), '-v', 'error', '-f', 'lavfi', '-i',
            'testsrc2=size=32x24:rate=2:duration=1', '-c:v', 'libx265',
            '-pix_fmt', 'yuv420p10le', '-y', str(source),
        ], check=True, capture_output=True)
        pipeline = VideoUpscalePipeline(UpscaleSettings(
            str(source), str(output), backend='precision', content_mode='anime',
            denoise='none', codec='h265_10', detail_preserve=70,
            hardware_encode=False, keep_cache=True,
        ), log=print)
        pipeline.run()
        metadata = json.loads(subprocess.check_output([
            find_ffprobe(), '-v', 'error', '-select_streams', 'v:0',
            '-show_entries', 'stream=width,height,pix_fmt', '-of', 'json', str(output),
        ]))['streams'][0]
        assert metadata == {'width': 64, 'height': 48, 'pix_fmt': 'yuv420p10le'}, metadata
        python = USER_DATA_DIR / 'precision/Scripts/python.exe'
        frame = next(pipeline.upscaled_frames.glob('*.png'))
        check = (
            "import cv2,numpy as np,sys; "
            "a=cv2.imdecode(np.fromfile(sys.argv[1],dtype=np.uint8),-1); "
            "assert a.dtype==np.uint16; "
            "assert np.any(a%257!=0), '8-bit quantization detected'; "
            "print('UINT16 PRECISION PASS')"
        )
        subprocess.run([str(python), '-c', check, str(frame)], check=True)
        print('PRECISION END-TO-END PASS', metadata)
        # Only remove the cache generated by this synthetic test.
        import shutil
        shutil.rmtree(pipeline.cache_dir)


if __name__ == '__main__':
    main()
